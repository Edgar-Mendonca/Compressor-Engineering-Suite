"""CalculiX input-deck export for independent checks of the built-in models.

``rotor_beam_deck`` writes a 3D beam model of the rotor (B32R elements,
equivalent square sections, point masses, SPRING1 bearing springs) with a
*FREQUENCY step, so the non-rotating natural frequencies of the built-in
FE model can be verified with CalculiX (``ccx -i rotor``).

``rotor_axisymmetric_deck`` writes an axisymmetric CAX4 mesh of the shaft
profile with a centrifugal load (*DLOAD CENTRIF) for shaft-body stresses.

Decks are plain text; running CalculiX is optional and external.
"""

from __future__ import annotations

import math
import shutil
import subprocess
from pathlib import Path


def rotor_beam_deck(model, bearing_k: float, title: str = "compsuite rotor") -> str:
    """B32R beam deck. Point masses are translational only (CalculiX 2.21 has
    no rotary inertia card for MASS elements), so compare with a built-in
    model whose disk inertias are zeroed (see tests)."""
    lines = ["** " + title, "** Generated by compsuite - beam model for natural-frequency verification", "*NODE, NSET=NALL"]
    z = model.nodes
    n = len(z)
    for i, zi in enumerate(z, start=1):
        lines.append(f"{i}, {zi:.6f}, 0.0, 0.0")
    for e in range(n - 1):  # mid-side nodes
        lines.append(f"{n + 1 + e}, {0.5 * (z[e] + z[e + 1]):.6f}, 0.0, 0.0")
    elsets = {}
    for e, L, sec in model.elements():
        key = (round(sec.od, 6), round(sec.id, 6))
        elsets.setdefault(key, []).append(e)
    for k, (key, els) in enumerate(elsets.items()):
        lines.append(f"*ELEMENT, TYPE=B32R, ELSET=SH{k}")
        for e in els:
            lines.append(f"{e + 1}, {e + 1}, {n + 1 + e}, {e + 2}")
    eid = n
    for pm in model.masses:
        lines.append(f"*ELEMENT, TYPE=MASS, ELSET=M{eid}")
        lines.append(f"{eid}, {model.node_at(pm.z) + 1}")
        lines.append(f"*MASS, ELSET=M{eid}")
        lines.append(f"{pm.mass:.6E}")
        eid += 1
    brg = [s for s in model.supports if s.kind == "bearing"]
    for b in brg:
        node = model.node_at(b.z) + 1
        for dof in (2, 3):
            lines.append(f"*ELEMENT, TYPE=SPRING1, ELSET=K{eid}")
            lines.append(f"{eid}, {node}")
            lines.append(f"*SPRING, ELSET=K{eid}")
            lines.append(f"{dof}")
            lines.append(f"{bearing_k:.6E}")  # CalculiX needs a decimal point here
            eid += 1
    # CalculiX 2.21 expands CIRC/PIPE beam sections inaccurately (about -27 %
    # on a simply supported bar). Each section is therefore exported as the
    # square with the same bending inertia, and its density is scaled so
    # the mass per unit length is unchanged.
    nu = model.E / (2 * model.G) - 1
    for k, (key, els) in enumerate(elsets.items()):
        od, idd = key
        I = math.pi / 64 * (od**4 - idd**4)
        A = math.pi / 4 * (od**2 - idd**2)
        a = (12 * I) ** 0.25
        lines += [f"*MATERIAL, NAME=MAT{k}", "*ELASTIC", f"{model.E:.6E}, {nu:.4f}", "*DENSITY",
                  f"{model.rho * A / a**2:.6E}"]
        lines.append(f"*BEAM SECTION, ELSET=SH{k}, MATERIAL=MAT{k}, SECTION=RECT")
        lines.append(f"{a:.6E}, {a:.6E}")
        lines.append("0.0, 1.0, 0.0")
    lines += ["*BOUNDARY", "1, 1, 1", "1, 4, 4"]
    lines += ["*STEP", "*FREQUENCY", "12", "*NODE FILE", "U", "*END STEP"]
    return "\n".join(lines) + "\n"


def rotor_axisymmetric_deck(rotor: dict, mat: dict, omega: float, dr: float = 0.005, dz: float = 0.01) -> str:
    """Structured CAX4 mesh of the shaft profile (r = x, z = y) with centrifugal load."""
    secs = rotor["sections"]
    zs = sorted({round(s["z0_m"], 6) for s in secs} | {round(s["z1_m"], 6) for s in secs})
    rs = sorted({0.0} | {round(s["od_m"] / 2, 6) for s in secs} | {round(s["id_m"] / 2, 6) for s in secs})

    def refine(pts, h):
        out = [pts[0]]
        for a, b in zip(pts[:-1], pts[1:]):
            n = max(1, math.ceil((b - a) / h))
            out += [a + (b - a) * k / n for k in range(1, n + 1)]
        return out
    zg, rg = refine(zs, dz), refine(rs, dr)
    def inside(rc, zc):
        for s in secs:
            if s["z0_m"] <= zc <= s["z1_m"] and s["id_m"] / 2 <= rc <= s["od_m"] / 2:
                return True
        return False
    node_id = {}
    lines = ["** compsuite axisymmetric rotor body (CAX4), centrifugal load", "*NODE, NSET=NALL"]
    elems = []
    for j in range(len(zg) - 1):
        for i in range(len(rg) - 1):
            rc, zc = 0.5 * (rg[i] + rg[i + 1]), 0.5 * (zg[j] + zg[j + 1])
            if inside(rc, zc):
                corners = [(i, j), (i + 1, j), (i + 1, j + 1), (i, j + 1)]
                ids = []
                for c in corners:
                    if c not in node_id:
                        node_id[c] = len(node_id) + 1
                    ids.append(node_id[c])
                elems.append(ids)
    for (i, j), nid in sorted(node_id.items(), key=lambda kv: kv[1]):
        lines.append(f"{nid}, {rg[i]:.6f}, {zg[j]:.6f}, 0.0")
    lines.append("*ELEMENT, TYPE=CAX4, ELSET=EALL")
    for k, ids in enumerate(elems, start=1):
        lines.append(f"{k}, {ids[0]}, {ids[1]}, {ids[2]}, {ids[3]}")
    axial_fix = min(node_id.items(), key=lambda kv: (abs(zg[kv[0][1]] - rotor["bearing_z_m"][-1]), kv[0][0]))[1]
    lines += ["*MATERIAL, NAME=SHAFT", "*ELASTIC", f"{mat['E_pa']:.6g}, {mat['poisson']}", "*DENSITY", f"{mat['density_kg_m3']}",
              "*SOLID SECTION, ELSET=EALL, MATERIAL=SHAFT", "*BOUNDARY", f"{axial_fix}, 2, 2",
              "*STEP", "*STATIC", "*DLOAD", f"EALL, CENTRIF, {omega**2:.6g}, 0., 0., 0., 0., 1., 0.",
              "*NODE FILE", "U", "*EL FILE", "S", "*END STEP"]
    return "\n".join(lines) + "\n"


def run_calculix(deck: str, workdir: Path, name: str = "rotor") -> dict:
    exe = shutil.which("ccx") or shutil.which("ccx_2.21") or shutil.which("ccx_2.20")
    workdir.mkdir(parents=True, exist_ok=True)
    (workdir / f"{name}.inp").write_text(deck)
    if not exe:
        return {"ran": False, "reason": "CalculiX executable 'ccx' not found", "deck": str(workdir / f"{name}.inp")}
    proc = subprocess.run([exe, "-i", name], cwd=workdir, capture_output=True, text=True, timeout=600)
    freqs = []
    dat = workdir / f"{name}.dat"
    if dat.exists():
        on = False
        for line in dat.read_text().splitlines():
            if "E I G E N V A L U E   O U T P U T" in line:
                on = True
                continue
            if on:
                parts = line.split()
                if len(parts) >= 4 and parts[0].isdigit():
                    freqs.append(float(parts[3]))
                elif freqs and not parts:
                    break
    return {"ran": True, "returncode": proc.returncode, "frequencies_hz": freqs, "stdout_tail": proc.stdout[-2000:]}
